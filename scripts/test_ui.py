"""Meaningful end-to-end checks. Run with the local server on port 5173."""
import json
from datetime import date, timedelta
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

OUT = Path('artifacts')
OUT.mkdir(exist_ok=True)
BASE = 'http://localhost:5173'
KEY = 'cung-hoc-v1'
results = []

def passed(name):
    results.append(name)
    print('PASS: ' + name)

with sync_playwright() as p:
    browser = p.chromium.launch(headless=True)
    context = browser.new_context(viewport={'width':1440,'height':1060}, accept_downloads=True)
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto(BASE)
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading',name='Tổng quan')).to_be_visible()
    data = page.evaluate(f'JSON.parse(localStorage.getItem("{KEY}"))')
    assert len(data['students']) == 20 and len(data['groups']) == 6
    passed('20 students, 20 parents, 4 topics and 6 groups seeded')

    page.goto(BASE+'/#students')
    page.locator('#list-search').fill('minh anh')
    expect(page.locator('.students-table tbody tr')).to_have_count(1)
    page.locator('#list-search').fill('thu huong')
    expect(page.locator('.students-table tbody tr')).to_have_count(1)
    passed('Student and parent search ignores Vietnamese diacritics')

    page.get_by_role('button',name='Thêm học sinh',exact=True).click()
    form = page.locator('#student-form')
    form.get_by_role('button',name='Thêm học sinh',exact=True).click()
    expect(form.locator('.form-error')).to_contain_text('bắt buộc')
    form.locator('[name=name]').fill('Nguyễn An Nhiên')
    form.locator('[name=parent]').fill('Nguyễn Thanh Bình')
    form.locator('[name=parentPhone]').fill('0912345678')
    form.get_by_role('button',name='Thêm học sinh',exact=True).click()
    expect(page.locator('dialog')).not_to_be_visible()
    page.locator('#list-search').fill('an nhien')
    expect(page.locator('.students-table tbody tr')).to_have_count(1)
    assert page.locator('a[aria-label="Gọi Nguyễn Thanh Bình"]').get_attribute('href') == 'tel:0912345678'
    assert page.locator('a[aria-label="Mở Zalo của Nguyễn Thanh Bình"]').get_attribute('href') == 'https://zalo.me/0912345678'
    passed('Add student; student phone optional; required validation; phone and Zalo links')

    page.goto(BASE+'/#topics')
    page.get_by_role('button',name='Tạo chuyên đề',exact=True).click()
    form = page.locator('#topic-form')
    form.locator('[name=name]').fill('Dự án vườn trường')
    form.locator('[name=due]').fill((date.today()+timedelta(days=10)).isoformat())
    form.locator('[name=description]').fill('Cùng thiết kế khu vườn xanh cho lớp.')
    form.locator('[name=subject]').select_option(label='Hoạt động trải nghiệm')
    form.locator('[name=color]').select_option('green')
    form.get_by_role('button',name='Tạo chuyên đề',exact=True).click()
    expect(page.get_by_role('heading',name='Dự án vườn trường',exact=True)).to_be_visible()
    passed('Create topic and open its detail')

    page.get_by_role('button',name='Tạo nhóm',exact=True).click()
    form = page.locator('#group-form')
    form.locator('[name=name]').fill('Nhóm mầm xanh')
    form.locator('#member-search').fill('minh anh')
    form.locator('input[name=member]').check()
    form.locator('#member-search').fill('an nhien')
    form.locator('input[name=member]').check()
    expect(form.locator('#selected-members .member-chip')).to_have_count(2)
    form.locator('#member-search').fill('gia bao')
    form.locator('input[name=member]').check()
    expect(form.locator('#selected-members .member-chip')).to_have_count(3)
    form.locator('#member-search').fill('')
    expect(form.locator('input[name=member]:checked')).to_have_count(3)
    data = page.evaluate(f'JSON.parse(localStorage.getItem("{KEY}"))')
    new_student = next(s for s in data['students'] if s['name']=='Nguyễn An Nhiên')
    form.locator('[name=hostId]').select_option(new_student['id'])
    expect(form.locator('[name=hostName]')).to_have_value('Nguyễn Thanh Bình')
    expect(form.locator('[name=hostPhone]')).to_have_value('0912345678')
    form.locator('[name=address]').fill('123 Đường Nguyễn Huệ, TP. Hồ Chí Minh')
    form.locator('[name=date]').fill(date.today().isoformat())
    form.locator('[name=start]').fill('18:30')
    form.locator('[name=end]').fill('17:30')
    form.get_by_role('button',name='Tạo nhóm học',exact=True).click()
    expect(form.locator('.form-error')).to_contain_text('Giờ kết thúc')
    form.locator('[name=end]').fill('20:00')
    expect(form.locator('#schedule-warning')).to_contain_text('trùng giờ')
    form.get_by_role('button',name='Tạo nhóm học',exact=True).click()
    expect(page.locator('#modal-title')).to_have_text('Nhóm mầm xanh')
    expect(page.locator('.detail-member')).to_have_count(3)
    maps = page.locator('a[href^="https://www.google.com/maps/search/"]')
    assert 'api=1&query=' in maps.get_attribute('href')
    passed('Cross-group membership; selection persists through search; host autofill; time validation; conflict warning; Maps')

    page.get_by_role('button',name='Sửa nhóm học',exact=True).click()
    form = page.locator('#group-form')
    expect(form.locator('input[name=member]:checked')).to_have_count(3)
    form.locator('[name=name]').fill('Nhóm mầm xanh mới')
    page.get_by_role('button',name='Đóng',exact=True).click()
    expect(page.locator('.discard-notice')).to_be_visible()
    page.get_by_role('button',name='Tiếp tục nhập',exact=True).click()
    form.get_by_role('button',name='Lưu nhóm học',exact=True).click()
    expect(page.locator('#modal-title')).to_have_text('Nhóm mầm xanh mới')
    page.get_by_role('button',name='Đóng',exact=True).click()
    page.reload()
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading',name='Nhóm mầm xanh mới')).to_be_visible()
    passed('Edit group; prevent discarding unsaved form; data persists after reload')

    page.goto(BASE+'/#students')
    page.locator('#list-search').fill('an nhien')
    page.get_by_role('button',name='Sửa Nguyễn An Nhiên',exact=True).click()
    form = page.locator('#student-form')
    form.locator('[name=parent]').fill('Nguyễn Thanh Bình mới')
    form.locator('[name=parentPhone]').fill('0987654321')
    form.get_by_role('button',name='Lưu thay đổi',exact=True).click()
    data = page.evaluate(f'JSON.parse(localStorage.getItem("{KEY}"))')
    new_group = next(g for g in data['groups'] if g['name']=='Nhóm mầm xanh mới')
    assert new_group['hostName']=='Nguyễn Thanh Bình mới' and new_group['hostPhone']=='0987654321'
    page.get_by_role('button',name='Xóa Nguyễn An Nhiên',exact=True).click()
    expect(page.locator('#toast')).to_contain_text('đang thuộc 1 nhóm')
    passed('Parent edits update host contact; deleting an assigned student is prevented')

    page.goto(BASE+'/#calendar')
    expect(page.locator('.big-calendar')).to_be_visible()
    expect(page.get_by_role('heading',name='Nhóm mầm xanh mới')).to_be_visible()
    page.get_by_role('button',name='Tháng sau',exact=True).click()
    page.get_by_role('button',name='Hôm nay',exact=True).click()
    expect(page.get_by_role('heading',name='Nhóm mầm xanh mới')).to_be_visible()
    page.screenshot(path=str(OUT/'calendar.png'),full_page=True)
    passed('Month navigation and selected-day agenda')

    page.keyboard.press('Control+k')
    page.locator('#global-search').fill('mam xanh')
    page.locator('.search-result').click()
    expect(page.locator('#modal-title')).to_have_text('Nhóm mầm xanh mới')
    page.get_by_role('button',name='Hoàn thành',exact=True).click()
    expect(page.locator('.card-top .status')).to_contain_text('Đã hoàn thành')
    page.get_by_role('button',name='Mở lại',exact=True).click()
    page.get_by_role('button',name='Đóng',exact=True).click()
    passed('Global search and complete/reopen a group')

    page.get_by_role('button',name='Dữ liệu & cài đặt',exact=True).click()
    with page.expect_download() as download_info:
        page.get_by_role('button',name='Xuất bản sao',exact=True).click()
    downloaded = download_info.value
    downloaded.save_as(OUT/'backup.json')
    backup = json.loads((OUT/'backup.json').read_text(encoding='utf-8'))
    assert len(backup['students'])==21 and len(backup['groups'])==7
    page.locator('#import-file').set_input_files({'name':'invalid.json','mimeType':'application/json','buffer':b'{"version":1}'})
    expect(page.locator('#toast')).to_contain_text('Tệp không hợp lệ')
    page.locator('#import-file').set_input_files(str(OUT/'backup.json'))
    expect(page.locator('#modal-title')).to_have_text('Nhập bản sao dữ liệu?')
    page.get_by_role('button',name='Nhập và thay thế',exact=True).click()
    passed('Backup download; reject invalid import; valid import requires confirmation')

    # Deep links retain filters when reloaded.
    page.goto(BASE+'/#groups?status=all&q=mam+xanh')
    expect(page.locator('#group-list .session-card')).to_have_count(1)
    expect(page.locator('#list-search')).to_have_value('mam xanh')
    passed('Reloadable search and filter links')

    page.goto(BASE+'/#groups')
    page.locator('#list-search').fill('mam xanh')
    page.get_by_role('button',name='Xem nhóm',exact=True).click()
    page.get_by_role('button',name='Xóa nhóm học',exact=True).click()
    expect(page.locator('#modal-title')).to_have_text('Xóa nhóm học?')
    page.get_by_role('button',name='Hủy',exact=True).click()
    expect(page.locator('#modal-title')).to_have_text('Nhóm mầm xanh mới')
    page.get_by_role('button',name='Xóa nhóm học',exact=True).click()
    page.get_by_role('button',name='Xóa nhóm',exact=True).click()
    expect(page.locator('#group-list .session-card')).to_have_count(0)
    passed('Delete group confirmation, cancel and final deletion')

    # Responsive and keyboard checks use a fresh context with only demo data.
    mobile = browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mp = mobile.new_page()
    mp.on('pageerror',lambda error: errors.append(str(error)))
    for route in ['overview','topics','groups','students','calendar']:
        mp.goto(BASE+'/#'+route)
        mp.wait_for_load_state('networkidle')
        assert not mp.evaluate('document.documentElement.scrollWidth > innerWidth'),route+' overflow'
        expect(mp.locator('#mobile-nav')).to_be_visible()
        mp.screenshot(path=str(OUT/f'mobile-{route}.png'),full_page=True)
    mp.goto(BASE+'/#groups')
    mp.get_by_role('button',name='Tạo nhóm học',exact=True).click()
    expect(mp.locator('#group-form')).to_be_visible()
    assert not mp.evaluate('document.querySelector("dialog").scrollWidth > document.querySelector("dialog").clientWidth')
    mp.locator('[name=name]').fill('Nhóm kiểm thử mobile')
    mp.locator('#member-search').fill('minh anh')
    mp.locator('input[name=member]').check()
    mp.locator('[name=hostId]').select_option('s1')
    mp.locator('#group-form').get_by_role('button',name='Tạo nhóm học',exact=True).click()
    expect(mp.locator('#modal-title')).to_have_text('Nhóm kiểm thử mobile')
    mp.screenshot(path=str(OUT/'mobile-group-detail.png'),full_page=True)
    passed('390px mobile: all screens have no horizontal overflow; create group via touch layout')
    mp.close();mobile.close()

    clean = browser.new_page(viewport={'width':1440,'height':1060})
    clean.goto(BASE)
    clean.wait_for_load_state('networkidle')
    clean.screenshot(path=str(OUT/'desktop.png'),full_page=True)
    clean.keyboard.press('Tab')
    assert clean.locator(':focus').get_attribute('class')=='skip-link'
    clean.keyboard.press('Enter')
    expect(clean.locator('#main')).to_be_focused()
    passed('Keyboard skip link reaches main content')
    assert not errors, errors
    passed('No uncaught JavaScript errors during all flows')
    (OUT/'test-results.json').write_text(json.dumps({'passed':results,'errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
    browser.close()

print(f'ALL {len(results)} CHECKS PASSED')
